/** 줄여 쓴 값을 실제 데이터와 같은 모양(성별·연령대별 표)으로 펼친다. */
function expand(row) {
  const [id, name, region, cat, lat, lng, base, peak, spread, fBias, kidArr, trend, yearly, crowd, buzz] = row;
  const interest = {};
  for (const b of AGE_BANDS) {
    for (const g of ['m', 'f']) {
      const genderFactor = g === 'f' ? fBias : 2 - fBias;
      const ageFactor = 0.35 + 0.65 * Math.exp(-((b.mid - peak) ** 2) / (2 * spread ** 2));
      interest[g + b.code] = Math.max(0, Math.min(100, Math.round(base * genderFactor * ageFactor)));
    }
  }
  return {
    id, name, region, cat, lat, lng,
    interest,
    kid: { toddler: kidArr[0], lower: kidArr[1], upper: kidArr[2] },
    trend, yearly, crowd, buzz,
    sample: true,
  };
}

export const PLACES = RAW.map(expand);
